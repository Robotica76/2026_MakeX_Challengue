"""2D layout of the MakeX Challenge 2026 "Storm Breaker" field.

Source: 2026 MakeX Challenge Storm Breaker Rules Guide V1.1 (2026.9), section 4.2-4.3.
Every element records where its numbers come from:
  - "rules p.N"  -> dimension stated in the rules guide (page number as printed).
  - "estimate"   -> position scaled from the top view (Fig 4.2-1, p.10, ~3.44 mm/px);
                    the rules give element sizes but rarely their placement. Verify
                    against the official building instructions (Appendix 9) and update.

Frame: origin at the field corner on the red side, bottom-left of Fig 4.2-1.
x points toward the blue side, y points up, angles CCW, all units in mm.
The field is mirror-symmetric about x = FIELD_W / 2; red elements are defined
once and blue ones are generated by mirroring.
"""

from dataclasses import dataclass, replace
from typing import List, Optional, Tuple

# --- Field (rules p.10) -------------------------------------------------------
FIELD_W = 4655.0
FIELD_H = 3055.0
FRAME_HEIGHT = 900.0
CX = FIELD_W / 2
CY = FIELD_H / 2

# --- Floor relief --------------------------------------------------------------
# The floor is a flat printed map: no ramps, steps or slopes. The rules describe
# the drive system as moving the robot "over a flat field surface" (p.55 T04) and
# the renders show only printed graphics (Fig 4.1, 4.2-1). Relief comes only from
# the structures below, each with a top height `z` (mm above the floor).
FLOOR_PROFILE = "flat"

# --- Element sizes (rules) ----------------------------------------------------
START_SIZE = 500.0                       # p.12
RESOURCE_W, RESOURCE_D = 1040.0, 318.0   # p.13 (985 nominal, 1040 overall in Fig 4.2-6)
EXCHANGE_W, EXCHANGE_D = 318.0, 214.0    # p.19
PIN_AREA_L, PIN_AREA_D = 995.0, 195.0    # p.14
CONE_POST_D = 40.0                       # p.17 (40 x 405 mm post)
CONE_POST_SPAN = 1280.0                  # p.15 Fig 4.2-9, distance between outer posts
STRATEGY_L, STRATEGY_W = 960.0, 215.0    # p.17
CENTRAL_L, CENTRAL_W = 640.0, 215.0      # p.21 Fig 4.2-17 (640 rack, top 455x86 + X mark)
X_MARK_W, X_MARK_D = 447.0, 86.0         # p.21 Fig 4.2-17
FORTRESS_SIZE = 640.0                    # p.21
FLAG_POLE_L = 120.0                      # p.15 (horizontal pole 120-160 mm)

# Strategy channel windows (p.18 Fig 4.2-14): 120 lead-in, 4 windows of 140 mm
# separated by 80 mm dividers, numbered from the outer (wall) end.
CHANNEL_LEAD, CHANNEL_WIN, CHANNEL_DIV = 120.0, 140.0, 80.0

# --- Estimated placements (Fig 4.2-1) ----------------------------------------
START_INSET = 75.0          # start areas sit ~75 mm in from both walls
RESOURCE_CX_OFFSET = 807.5  # resource area centre is this far from the centre line
RESOURCE_FLOOR_D = RESOURCE_D - EXCHANGE_D  # mesh/back band under the shelf
FORTRESS_CX = 662.0         # red fortress centre x
CONE_POST_X = 200.0
STRATEGY_PROP_PITCH = 224.0  # spacing of the 4 prop spots on top of a strategy area


@dataclass(frozen=True)
class Element:
    name: str
    kind: str            # obstacle | movable | zone | overhead | no_touch | slot | prop
    alliance: str        # red | blue | neutral
    shape: str           # rect | circle
    x: float             # centre
    y: float
    w: float = 0.0       # rect size along x
    h: float = 0.0       # rect size along y
    r: float = 0.0       # circle radius
    label: str = ""
    source: str = "estimate"
    z: float = 0.0       # top height above the floor, mm (0 = flat floor marking)

    def bounds(self) -> Tuple[float, float, float, float]:
        """Axis-aligned bounds (xmin, ymin, xmax, ymax)."""
        if self.shape == "circle":
            return self.x - self.r, self.y - self.r, self.x + self.r, self.y + self.r
        return self.x - self.w / 2, self.y - self.h / 2, self.x + self.w / 2, self.y + self.h / 2

    def contains(self, px: float, py: float) -> bool:
        if self.shape == "circle":
            return (px - self.x) ** 2 + (py - self.y) ** 2 <= self.r ** 2
        x0, y0, x1, y1 = self.bounds()
        return x0 <= px <= x1 and y0 <= py <= y1


def rect(name, kind, alliance, x, y, w, h, label="", source="estimate") -> Element:
    return Element(name, kind, alliance, "rect", x, y, w=w, h=h, label=label, source=source)


def circle(name, kind, alliance, x, y, r, label="", source="estimate") -> Element:
    return Element(name, kind, alliance, "circle", x, y, r=r, label=label, source=source)


def _red_side() -> List[Element]:
    e: List[Element] = []
    half = START_SIZE / 2
    for i, y in enumerate((START_INSET + half, FIELD_H - START_INSET - half), start=1):
        e.append(rect(f"red_start_{i}", "zone", "red", START_INSET + half, y,
                      START_SIZE, START_SIZE, f"Start {i}", "rules p.12 size; estimate position"))

    # Own resource areas, against the side walls. The shelf (758 mm high) overhangs
    # the field; the bonus exchange pad is on the floor under it (p.19), with the
    # mesh/back structure behind the pad treated as a floor obstacle.
    rx = CX - RESOURCE_CX_OFFSET
    for i, (wall_y, sign) in enumerate(((0.0, 1), (FIELD_H, -1)), start=1):
        e.append(rect(f"red_resource_{i}", "overhead", "red", rx, wall_y + sign * RESOURCE_D / 2,
                      RESOURCE_W, RESOURCE_D, f"Resource {i}", "rules p.13 size; estimate position"))
        e.append(rect(f"red_resource_{i}_back", "obstacle", "red", rx,
                      wall_y + sign * RESOURCE_FLOOR_D / 2, RESOURCE_W, RESOURCE_FLOOR_D,
                      "", "estimate"))
        e.append(rect(f"red_exchange_{i}", "zone", "red", rx,
                      wall_y + sign * (RESOURCE_FLOOR_D + EXCHANGE_D / 2), EXCHANGE_W, EXCHANGE_D,
                      f"Bonus {i}", "rules p.19 size; estimate position"))
        for k, dx in enumerate((-RESOURCE_W / 2, -186.5, 186.5, RESOURCE_W / 2)):
            e.append(circle(f"red_resource_{i}_leg_{k}", "obstacle", "red", rx + dx,
                            wall_y + sign * (RESOURCE_D - 20), 20, "", "estimate"))

    # Pin placement area against the back wall, cone posts and flag poles beside it.
    e.append(rect("red_pin_area", "obstacle", "red", PIN_AREA_D / 2, CY, PIN_AREA_D, PIN_AREA_L,
                  "Pins", "rules p.14 size; estimate position"))
    for i, sign in enumerate((1, -1), start=1):
        e.append(circle(f"red_cone_post_{i}", "obstacle", "red", CONE_POST_X,
                        CY + sign * CONE_POST_SPAN / 2, CONE_POST_D / 2, f"Cone {i}",
                        "rules p.15/17; estimate x"))
        e.append(rect(f"red_flag_{i}", "overhead", "red", FLAG_POLE_L / 2,
                      CY + sign * (PIN_AREA_L / 2 + 20), FLAG_POLE_L, 15, f"Flag {i}",
                      "rules p.15 (961 mm high); estimate position"))

    e.append(rect("red_fortress", "movable", "red", FORTRESS_CX, CY, FORTRESS_SIZE, FORTRESS_SIZE,
                  "Fortress", "rules p.21 size; estimate position"))
    return e


def _neutral() -> List[Element]:
    e: List[Element] = [
        rect("central_resource", "obstacle", "neutral", CX, CY, CENTRAL_W, CENTRAL_L,
             "", "rules p.21; estimate position"),
        rect("x_mark", "no_touch", "neutral", CX, CY, X_MARK_W, X_MARK_D, "X",
             "rules p.21, R24"),
    ]
    for side, sign in (("upper", 1), ("lower", -1)):
        sy = CY + sign * (CENTRAL_L / 2 + STRATEGY_L / 2)
        e.append(rect(f"strategy_{side}", "obstacle", "neutral", CX, sy, STRATEGY_W, STRATEGY_L,
                      "", "rules p.17 size; estimate position"))
        # Central barrier (named in R02) closing the gap from the strategy area to the wall.
        gap = FIELD_H / 2 - CENTRAL_L / 2 - STRATEGY_L
        e.append(rect(f"barrier_{side}", "obstacle", "neutral", CX, CY + sign * (FIELD_H / 2 - gap / 2),
                      STRATEGY_W, gap, "", "R02 p.64; estimate geometry"))
        # Channel windows for letter cubes, numbered from the wall end (MAKE order).
        outer = sy + sign * STRATEGY_L / 2
        for i, letter in enumerate("MAKE"):
            off = CHANNEL_LEAD + CHANNEL_WIN / 2 + i * (CHANNEL_WIN + CHANNEL_DIV)
            e.append(rect(f"strategy_{side}_channel_{i + 1}", "slot", "neutral", CX,
                          outer - sign * off, STRATEGY_W, CHANNEL_WIN, letter, "rules p.18, p.39"))
    return e


# Default prop layout as drawn in Fig 4.2-1 / 4.2-13. The real layout is drawn from
# one of 10 prop cards before each match (p.51, Appendix 8); X values are placeholders.
DEFAULT_PROP_LAYOUT = {
    "upper": ("cone", "X3", "X6", "cone"),
    "lower": ("cone", "X9", "X12", "cone"),
}


def strategy_props(layout: Optional[dict] = None) -> List[Element]:
    layout = layout or DEFAULT_PROP_LAYOUT
    e: List[Element] = []
    for side, sign in (("upper", 1), ("lower", -1)):
        sy = CY + sign * (CENTRAL_L / 2 + STRATEGY_L / 2)
        for i, prop in enumerate(layout[side]):
            y = sy + (1.5 - i) * STRATEGY_PROP_PITCH * sign
            size = 120.0  # cone base and bonus cube are both 120 mm (p.24-25)
            e.append(rect(f"prop_{side}_{i + 1}", "prop", "neutral", CX, y, size, size, prop,
                          "rules p.24-25 size; position from prop card"))
    return e


# Top heights above the floor (mm), matched by name suffix (alliance, side and
# index tokens ignored), longest match first.
# Values from the rules drawings; intermediate levels are kept in the comments.
HEIGHTS_MM = {
    "resource": 965.0,          # p.13 Fig 4.2-6: pin/ball shelf underside ~758 mm
    "resource_back": 965.0,
    "leg": 965.0,
    "pin_area": 405.0,          # p.15 Fig 4.2-9: placement shelf at 405 mm
    "cone_post": 405.0,         # p.17
    "flag": 961.0,              # p.15: flag pole height
    "fortress": 646.0,          # p.21: letter level 171 mm, ball basket 407 mm
    "central_resource": 654.0,  # p.21 Fig 4.2-17: ball levels ~200 mm apart
    "x_mark": 947.0,            # p.21 Fig 4.2-17: X spans 654-947 mm
    "strategy": 259.0,          # p.17: channel opening 254 mm (Fig 4.2-14)
    "barrier": 259.0,           # estimate: same frame as the strategy area
    "cone": 170.0,              # p.25
    "cube": 120.0,              # p.24-25
}


def _height(el: Element) -> float:
    if el.kind == "prop":
        return HEIGHTS_MM["cone"] if el.label == "cone" else HEIGHTS_MM["cube"]
    if el.kind == "slot":
        return 0.0
    parts = [p for p in el.name.split("_")
             if not p.isdigit() and p not in ("red", "blue", "upper", "lower")]
    for n in range(len(parts)):
        key = "_".join(parts[n:])
        if key in HEIGHTS_MM:
            return HEIGHTS_MM[key]
    return 0.0


def mirror(el: Element) -> Element:
    return replace(el, name=el.name.replace("red_", "blue_", 1), alliance="blue",
                   x=FIELD_W - el.x)


def build_field(prop_layout: Optional[dict] = None) -> List[Element]:
    red = _red_side()
    elements = red + [mirror(el) for el in red] + _neutral() + strategy_props(prop_layout)
    return [replace(el, z=_height(el)) for el in elements]


# Movement boundary (p.11 Fig 4.2-3): each alliance's robots and fortress stay on
# their own side; the strategy/central strip in the middle belongs to neither.
def alliance_x_limits(alliance: str) -> Tuple[float, float]:
    if alliance == "red":
        return 0.0, CX - STRATEGY_W / 2
    return CX + STRATEGY_W / 2, FIELD_W


def get(elements: List[Element], name: str) -> Element:
    for el in elements:
        if el.name == name:
            return el
    raise KeyError(name)
